export const ISSUES: Record<string, IssueDef> = Object.fromEntries(defs.map((d) => [d.code, d]));

/** Error codes whose URL is a page. Site-wide errors report against the homepage, and a broken resource's URL is the file itself. */
export const PAGE_ERROR_CODES = defs.filter((d) => d.severity === "error" && !d.site && d.code !== "broken-resources").map((d) => d.code);
export const ISSUE_LIST: readonly IssueDef[] = defs;

export function issueDef(code: string): IssueDef | undefined {
  return ISSUES[code];
}
