/**
 * SEOpen's own site-audit issue taxonomy. Each issue has a stable code (stored in audit_issues),
 * a category, a severity, and plain-English "why it matters / how to fix" text.
 * Detection lives in issues.ts; this file is data only so pages can import it cheaply.
 */

export type Severity = "error" | "warning" | "notice";

